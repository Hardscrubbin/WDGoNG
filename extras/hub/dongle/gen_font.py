#!/usr/bin/env python3
"""Render ASCII 32..126 into a 6x10 1-bit font header (main/font.h). Needs Pillow.
Run once; the generated header is committed."""
from PIL import Image, ImageDraw, ImageFont
W, H = 6, 10
font = ImageFont.truetype("/System/Library/Fonts/Monaco.ttf", 10)
rows = []
for c in range(32, 127):
    im = Image.new("L", (W, H), 0)
    ImageDraw.Draw(im).text((0, -2), chr(c), fill=255, font=font)
    g = []
    for y in range(H):
        b = 0
        for x in range(W):
            if im.getpixel((x, y)) > 96:
                b |= 0x80 >> x
        g.append(b)
    rows.append("  {%s}, /* %s */" % (",".join("0x%02x" % v for v in g), chr(c) if c not in (92,) else "backslash"))
open("main/font.h", "w").write(
    "/* generated by gen_font.py - 6x10 glyphs, ASCII 32..126, MSB = left pixel */\n"
    "#pragma once\n#include <stdint.h>\n#define FONT_W 6\n#define FONT_H 10\n"
    "static const uint8_t font6x10[95][10] = {\n" + "\n".join(rows) + "\n};\n")
print("font.h written")
